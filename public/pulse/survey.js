let cat;
try {
  const r = await fetch('/api/survey/catalogue');
  if (!r.ok) throw new Error('HTTP ' + r.status);
  cat = await r.json();
} catch (e) {
  document.body.insertAdjacentHTML('beforeend', '<p style="font-family:monospace;color:#ff5a5a;padding:24px">Could not load the survey. Please reload.</p>');
  throw e;
}

export const SURVEY = { ...cat.SURVEY, ui: UI };
export const GEO = cat.GEO;

export function allQuestions(survey = SURVEY) {
  const out = [survey.player];
  for (const level of survey.levels) out.push(...level.questions);
  out.push(survey.boss.question);
  out.push({ id: survey.card.sector.id, type: 'single', optional: true, options: survey.card.sector.options });
  out.push({ id: survey.card.size.id, type: 'single', optional: true, options: survey.card.size.options });
  return out;
}
